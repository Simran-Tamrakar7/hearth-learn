#!/usr/bin/env node
/** Build step: <slug>/part-N/chapter-M.md → compiled.body.ts (source of truth = markdown on disk) */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const manualsRoot = path.join(root, "src/app/manuals");
const SLUGS = ["playwright", "testing-types"];

function parseValue(raw) {
  const v = raw.trim();
  if (!v) return "";
  if (v.startsWith("[") || v.startsWith("{")) {
    try {
      return JSON.parse(v);
    } catch {
      return v;
    }
  }
  if ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'"))) {
    try {
      return JSON.parse(v);
    } catch {
      return v.slice(1, -1);
    }
  }
  return v;
}

function parseFrontmatter(raw) {
  const m = /^---\r?\n([\s\S]*?)\r?\n---\r?\n([\s\S]*)$/.exec(raw);
  if (!m) return { meta: {}, body: raw.trim() };
  const meta = {};
  for (const line of m[1].split("\n")) {
    const kv = /^([\w]+):\s*(.+)$/.exec(line.trim());
    if (!kv) continue;
    meta[kv[1]] = parseValue(kv[2]);
  }
  return { meta, body: m[2].trim() };
}

function loadManualFromMd(slug) {
  const manualDir = path.join(manualsRoot, slug);
  const metaPath = path.join(manualDir, "meta.json");
  if (!fs.existsSync(metaPath)) throw new Error(`missing meta.json for ${slug}`);
  const meta = JSON.parse(fs.readFileSync(metaPath, "utf8"));
  const chapters = [];
  const partDirs = fs
    .readdirSync(manualDir)
    .filter((d) => /^part-\d+$/.test(d))
    .sort((a, b) => parseInt(a.split("-")[1], 10) - parseInt(b.split("-")[1], 10));

  for (const partDir of partDirs) {
    const pn = parseInt(partDir.split("-")[1], 10);
    const fullPart = path.join(manualDir, partDir);
    const files = fs
      .readdirSync(fullPart)
      .filter((f) => /^chapter-\d+\.md$/.test(f))
      .sort((a, b) => parseInt(a.match(/\d+/)[0], 10) - parseInt(b.match(/\d+/)[0], 10));
    for (const file of files) {
      const { meta: fm, body } = parseFrontmatter(fs.readFileSync(path.join(fullPart, file), "utf8"));
      const partName = fm.partName || `Part ${pn}`;
      const overview = fm.overviewText ? String(fm.overviewText) : body.split("\n\n")[0]?.slice(0, 500) || "";
      chapters.push({
        id: fm.id || `${slug}-${pn}-${file}`,
        phase: partName,
        title: fm.title || file,
        minutes: fm.minutes || 20,
        level: fm.level || "beginner",
        overlayNo: fm.overlayNo,
        overviewText: overview,
        why: fm.why,
        when: fm.when,
        practical: fm.practical,
        advantages: fm.advantages,
        limitations: fm.limitations,
        tools: Array.isArray(fm.tools) ? fm.tools : [],
        contentMarkdown: body,
        steps: [],
        learn: [],
      });
    }
  }

  return { ...meta, chapters };
}

for (const slug of SLUGS) {
  const body = loadManualFromMd(slug);
  const out = path.join(manualsRoot, slug, "compiled.body.ts");
  fs.writeFileSync(
    out,
    `/** Auto-generated by scripts/compile-manuals-from-md.mjs — edit part-N/chapter-M.md instead */\nexport const pathwiseManual = ${JSON.stringify(body, null, 2)} as Record<string, unknown>;\n`,
    "utf8"
  );
  console.log(`compiled ${slug}: ${body.chapters.length} chapters`);
}
