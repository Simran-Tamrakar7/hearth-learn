#!/usr/bin/env node
/** Generate chapters-manifest.ts (paths + chapter imports) for each manual under types/ */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const manualsRoot = path.join(root, "src/app/manuals");
const SLUGS = ["testing-types", "playwright", "hearth-manual"];

for (const slug of SLUGS) {
  const manualDir = path.join(manualsRoot, "types", slug);
  const imports = [];
  const refs = [];
  const pathEntries = [];
  const partDirs = fs
    .readdirSync(manualDir)
    .filter((d) => /^part-\d+$/.test(d))
    .sort((a, b) => parseInt(a.split("-")[1], 10) - parseInt(b.split("-")[1], 10));

  for (const partDir of partDirs) {
    const files = fs
      .readdirSync(path.join(manualDir, partDir))
      .filter((f) => /^chapter-\d+\.ts$/.test(f))
      .sort((a, b) => parseInt(a.match(/\d+/)[0], 10) - parseInt(b.match(/\d+/)[0], 10));
    for (const file of files) {
      const rel = `${partDir}/${file}`;
      const full = path.join(manualDir, rel);
      const raw = fs.readFileSync(full, "utf8");
      const idMatch = raw.match(/"id"\s*:\s*"([^"]+)"/);
      const id = idMatch?.[1];
      if (id) pathEntries.push([id, rel]);

      const base = file.replace(".ts", "").replace("-", "_");
      const varName = `${partDir.replace("-", "_")}_${base}`;
      imports.push(`import { chapter as ${varName} } from "./${partDir}/${file.replace(".ts", "")}";`);
      refs.push(varName);
    }
  }

  const manifestOut = `// ⚙️ AUTO-GENERATED by scripts/generate-chapter-index.mjs — do not edit by hand
import type { ChapterRecord } from "../../types";

${imports.join("\n")}

export const chapterPaths: Record<string, string> = {
${pathEntries.map(([id, rel]) => `  ${JSON.stringify(id)}: ${JSON.stringify(rel)},`).join("\n")}
};

export const chapters: ChapterRecord[] = [
  ${refs.join(",\n  ")}
];
`;
  fs.writeFileSync(path.join(manualDir, "chapters-manifest.ts"), manifestOut, "utf8");

  for (const legacy of ["chapters-index.ts", "chapter-paths.ts"]) {
    const legacyPath = path.join(manualDir, legacy);
    if (fs.existsSync(legacyPath)) fs.unlinkSync(legacyPath);
  }

  console.log(`${slug}: chapters-manifest.ts (${refs.length} chapters)`);
}
